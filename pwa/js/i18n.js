export function detectLang(nav = (typeof navigator !== 'undefined' ? navigator : null)) {
  const l = ((nav && (nav.languages?.[0] || nav.language)) || 'en').toLowerCase();
  return l.startsWith('ru') || l.startsWith('uk') || l.startsWith('be') ? 'ru' : 'en';
}

export function t(lang, key, params = {}) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

// a { ru, en } text from the device
export function pick(text, lang) {
  if (typeof text === 'string') return text;
  if (!text || typeof text !== 'object') return '';
  const v = text[lang] ?? text.en ?? Object.values(text).find((x) => typeof x === 'string');
  return typeof v === 'string' ? v : '';
}

export const errKeyFor = (code, detail) => {
  const name = Object.keys(ERR).find((k) => ERR[k] === code);
  if (name === 'BAD_BUNDLE' && STRINGS.en[`err.bad_bundle.${detail}`]) return `err.bad_bundle.${detail}`;
  return name ? `err.${name.toLowerCase()}` : 'err.unknown';
};

